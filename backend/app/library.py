FREQUENCIES = [
    "Annual", "Quarterly", "Monthly", "Weekly", "Daily",
    "Multiple times per day", "Event-driven", "Continuous (automated)",
]


def _t(ref, domain, title, description, objective, risk, frequency, nature,
       attributes, dni, toe, evidence):
    return {
        "ref": ref,
        "domain": domain,
        "title": title,
        "description": description,
        "objective": objective,
        "risk": risk,
        "frequency": frequency,
        "nature": nature,  # Manual | Automated | IT-dependent manual
        "attributes": [{"id": f"A{i+1}", "text": a} for i, a in enumerate(attributes)],
        "dni_procedures": dni,
        "toe_procedures": toe,
        "expected_evidence": evidence,
    }


